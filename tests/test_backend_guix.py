"""Acceptance tests for the Guix deployment adapter.

These follow the assertions in docs/INSTALLER-HANDOFF.md section 8: a plan that
is not confirmed must not produce a handoff, one installation must have exactly
one backend, and no user text may become a shell command.
"""

from __future__ import annotations

import copy
import hashlib
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from wsm_install.backend_guix import (  # noqa: E402
    HandoffError,
    TargetSelection,
    prepare,
)
from wsm_install.plan import build_plan, canonical_json  # noqa: E402

FIXTURE = ROOT / "tests" / "fixtures" / "hardware" / "desktop-observed.json"


def selection(**overrides: str) -> TargetSelection:
    values = {
        "disk": "/dev/vda",
        "hostname": "wsm",
        "timezone": "Europe/Kyiv",
        "locale": "en_US.utf8",
        "keyboard_layout": "us",
        "username": "wsmuser",
        "full_name": "WSM User",
        "root_label": "wsm-root",
        "efi_label": "wsm-efi",
        "boot_mode": "efi",
    }
    values.update(overrides)
    return TargetSelection(**values)


def confirmed_plan(backend: str = "guix") -> dict:
    """A plan as the frontend would hand it over after the user's selections."""
    report_bytes = FIXTURE.read_bytes()
    report = json.loads(report_bytes)
    plan, _, _ = build_plan(report, report_bytes, backend)
    plan = copy.deepcopy(plan)
    plan["blockers"] = []
    plan["plan_readiness"]["confirmable"] = True
    plan["plan_readiness"]["missing_required_roles"] = []
    plan["plan_readiness"]["required_user_actions"] = []
    plan.pop("plan_sha256")
    plan["plan_sha256"] = hashlib.sha256(
        canonical_json(plan).encode("utf-8")
    ).hexdigest()
    return plan


def refresh_plan_hash(plan: dict) -> None:
    """Recompute the digest after a test deliberately changes a plan."""
    plan.pop("plan_sha256", None)
    plan["plan_sha256"] = hashlib.sha256(
        canonical_json(plan).encode("utf-8")
    ).hexdigest()


def handoff(plan: dict, target: TargetSelection, **kwargs):
    return prepare(
        plan,
        target,
        confirmed_plan_sha256=plan["plan_sha256"],
        confirmed_target_digest=target.digest(),
        **kwargs,
    )


def _paren_balance(text: str) -> int:
    """Count parentheses outside strings and comments; 0 means balanced."""
    depth = 0
    in_string = False
    escaped = False
    in_comment = False
    for character in text:
        if in_comment:
            in_comment = character != "\n"
            continue
        if in_string:
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == '"':
                in_string = False
            continue
        if character == ";":
            in_comment = True
        elif character == '"':
            in_string = True
        elif character == "(":
            depth += 1
        elif character == ")":
            depth -= 1
    return depth


class HandoffSuccessTests(unittest.TestCase):
    def test_confirmed_plan_produces_handoff(self) -> None:
        plan = confirmed_plan()
        result = handoff(plan, selection())
        self.assertEqual(result.backend_id, "guix-system")
        self.assertEqual(result.plan_sha256, plan["plan_sha256"])
        self.assertEqual(
            result.argv,
            ("guix", "system", "init", "/run/wsm/system.scm", "/mnt"),
        )

    def test_configuration_carries_ownership(self) -> None:
        text = handoff(confirmed_plan(), selection()).configuration
        self.assertIn("(host-name \"wsm\")", text)
        self.assertIn("grub-efi-bootloader", text)
        self.assertIn("(file-system-label \"wsm-root\")", text)
        self.assertIn("(name \"wsmuser\")", text)
        self.assertIn(confirmed_plan()["source_report"]["report_id"], text)

    def test_bios_target_uses_disk_bootloader(self) -> None:
        text = handoff(confirmed_plan(), selection(boot_mode="bios")).configuration
        self.assertIn("(bootloader grub-bootloader)", text)
        self.assertIn("(targets (list \"/dev/vda\"))", text)
        self.assertNotIn("/boot/efi", text)

    def test_configuration_is_well_formed_scheme(self) -> None:
        text = handoff(confirmed_plan(), selection()).configuration
        self.assertTrue(text.startswith(";; Generated by the WSM Guix"))
        self.assertEqual(_paren_balance(text), 0, "unbalanced parentheses")
        self.assertIn("(operating-system", text)

    def test_argv_is_a_typed_list(self) -> None:
        result = handoff(confirmed_plan(), selection())
        self.assertIsInstance(result.argv, tuple)
        for element in result.argv:
            self.assertIsInstance(element, str)
            self.assertNotIn("\n", element)

    def test_nixos_deployment_is_unreachable(self) -> None:
        result = handoff(confirmed_plan(), selection())
        joined = " ".join(result.argv)
        self.assertNotIn("nixos-install", joined)
        self.assertNotIn("nix", joined.replace("guix", ""))

    def test_quotes_in_full_name_cannot_break_the_scheme(self) -> None:
        text = handoff(
            confirmed_plan(), selection(full_name='Ada "the" Lovelace')
        ).configuration
        self.assertIn('(comment "Ada \\"the\\" Lovelace")', text)


class HandoffRefusalTests(unittest.TestCase):
    def assert_refused(self, code: str, plan: dict, target: TargetSelection, **kwargs) -> None:
        with self.assertRaises(HandoffError) as caught:
            handoff(plan, target, **kwargs)
        self.assertEqual(caught.exception.code, code)

    def test_diagnostic_plan_is_refused(self) -> None:
        report_bytes = FIXTURE.read_bytes()
        plan, _, _ = build_plan(json.loads(report_bytes), report_bytes, "guix")
        self.assert_refused("plan.not_confirmable", plan, selection())

    def test_plan_payload_must_match_its_digest(self) -> None:
        plan = confirmed_plan()
        plan["warnings"].append("post-confirmation mutation")
        self.assert_refused("plan.digest_mismatch", plan, selection())

    def test_rehashed_plan_still_requires_the_original_confirmation(self) -> None:
        plan = confirmed_plan()
        confirmed = plan["plan_sha256"]
        plan["warnings"].append("user confirmation was for an earlier plan")
        refresh_plan_hash(plan)
        with self.assertRaises(HandoffError) as caught:
            prepare(
                plan,
                selection(),
                confirmed_plan_sha256=confirmed,
                confirmed_target_digest=selection().digest(),
            )
        self.assertEqual(caught.exception.code, "handoff.plan_changed")

    def test_source_report_id_rejects_scheme_comment_injection(self) -> None:
        plan = confirmed_plan()
        plan["source_report"]["report_id"] = "report-id-valid-0001\\n(define injected #t)"
        refresh_plan_hash(plan)
        self.assert_refused("plan.provenance.report_id", plan, selection())

    def test_source_report_sha256_rejects_scheme_comment_injection(self) -> None:
        plan = confirmed_plan()
        plan["source_report"]["sha256"] = "a" * 64 + "\\n(define injected #t)"
        refresh_plan_hash(plan)
        self.assert_refused("plan.provenance.sha256", plan, selection())

    def test_source_report_requires_an_object(self) -> None:
        plan = confirmed_plan()
        plan["source_report"] = ["report-id-valid-0001", "a" * 64]
        refresh_plan_hash(plan)
        self.assert_refused("plan.provenance", plan, selection())

    def test_source_report_rejects_non_string_provenance(self) -> None:
        mutations = (
            ("report_id", 123, "plan.provenance.report_id"),
            ("sha256", ["a" * 64], "plan.provenance.sha256"),
        )
        for field, value, code in mutations:
            with self.subTest(field=field):
                plan = confirmed_plan()
                plan["source_report"][field] = value
                refresh_plan_hash(plan)
                self.assert_refused(code, plan, selection())

    def test_device_path_rejects_dot_segments_and_trailing_newline(self) -> None:
        for disk in ("/dev/.", "/dev/..", "/dev/vda\\n", "/dev/vda/../../etc/passwd"):
            with self.subTest(disk=disk):
                self.assert_refused("selection.disk", confirmed_plan(), selection(disk=disk))

    def test_full_name_rejects_control_and_format_characters(self) -> None:
        for full_name in ("Ada\\rLovelace", "Ada\\tLovelace", "Ada\\x00Lovelace", "Ada\\u2028Lovelace", "Ada\\u202eLovelace", "Ada\\ud800Lovelace"):
            with self.subTest(full_name=repr(full_name)):
                self.assert_refused("selection.full_name", confirmed_plan(), selection(full_name=full_name))

    def test_target_selection_digest_is_unambiguous(self) -> None:
        left = selection(full_name="Ada|Lovelace", root_label="wsm-root")
        right = selection(full_name="Ada", root_label="Lovelace|wsm-root")
        self.assertNotEqual(left.digest(), right.digest())

    def test_configuration_path_must_be_installer_owned(self) -> None:
        for path in ("system.scm", "/etc/passwd", "/run/wsm/../../etc/passwd"):
            with self.subTest(path=path):
                with self.assertRaises(HandoffError) as caught:
                    handoff(confirmed_plan(), selection(), configuration_path=path)
                self.assertEqual(caught.exception.code, "argv.config_path")

    def test_target_mountpoint_must_be_installer_owned(self) -> None:
        for mountpoint in ("/", "/tmp/target", "/mnt/../", "/mnt/wsm"):
            with self.subTest(mountpoint=mountpoint):
                with self.assertRaises(HandoffError) as caught:
                    handoff(confirmed_plan(), selection(), target_mountpoint=mountpoint)
                self.assertEqual(caught.exception.code, "argv.mountpoint")

    def test_blockers_stop_the_handoff(self) -> None:
        plan = confirmed_plan()
        plan["blockers"] = ["boot-path: required critical device discovery is unknown"]
        refresh_plan_hash(plan)
        self.assert_refused("plan.blockers", plan, selection())

    def test_other_backend_is_refused(self) -> None:
        plan = confirmed_plan(backend="nix")
        self.assert_refused("plan.backend", plan, selection())

    def test_disk_access_already_performed_is_refused(self) -> None:
        plan = confirmed_plan()
        plan["execution"]["disk_access_performed"] = True
        refresh_plan_hash(plan)
        self.assert_refused("plan.disk_access", plan, selection())

    def test_second_bootloader_owner_is_refused(self) -> None:
        self.assert_refused(
            "handoff.bootloader_owner",
            confirmed_plan(),
            selection(),
            external_bootloader_job=True,
        )

    def test_dot_device_paths_are_refused(self) -> None:
        for disk in ("/dev/.", "/dev/.."):
            with self.subTest(disk=disk):
                self.assert_refused(
                    "selection.disk", confirmed_plan(), selection(disk=disk)
                )

    def test_shell_metacharacters_in_disk_are_refused(self) -> None:
        self.assert_refused(
            "selection.disk", confirmed_plan(), selection(disk="/dev/vda; rm -rf /")
        )

    def test_scheme_injection_in_hostname_is_refused(self) -> None:
        self.assert_refused(
            "selection.hostname",
            confirmed_plan(),
            selection(hostname='wsm") (system* "rm" "-rf" "/'),
        )

    def test_username_must_be_an_account_name(self) -> None:
        self.assert_refused(
            "selection.username", confirmed_plan(), selection(username="root; id")
        )

    def test_identical_filesystem_labels_are_refused(self) -> None:
        self.assert_refused(
            "selection.label_collision",
            confirmed_plan(),
            selection(efi_label="wsm-root"),
        )

    def test_unknown_boot_mode_is_refused(self) -> None:
        self.assert_refused(
            "selection.boot_mode", confirmed_plan(), selection(boot_mode="coreboot")
        )

    def test_plan_changed_after_confirmation(self) -> None:
        plan = confirmed_plan()
        with self.assertRaises(HandoffError) as caught:
            prepare(
                plan,
                selection(),
                confirmed_plan_sha256="0" * 64,
                confirmed_target_digest=selection().digest(),
            )
        self.assertEqual(caught.exception.code, "handoff.plan_changed")

    def test_target_changed_after_confirmation(self) -> None:
        plan = confirmed_plan()
        with self.assertRaises(HandoffError) as caught:
            prepare(
                plan,
                selection(disk="/dev/vdb"),
                confirmed_plan_sha256=plan["plan_sha256"],
                confirmed_target_digest=selection().digest(),
            )
        self.assertEqual(caught.exception.code, "handoff.target_changed")

    def test_relative_configuration_path_is_refused(self) -> None:
        with self.assertRaises(HandoffError) as caught:
            handoff(confirmed_plan(), selection(), configuration_path="system.scm")
        self.assertEqual(caught.exception.code, "argv.config_path")


if __name__ == "__main__":
    unittest.main()
